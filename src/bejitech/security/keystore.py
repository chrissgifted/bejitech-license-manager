"""Where the data encryption key (DEK) lives.

* KeychainKeyStore: macOS Keychain (Windows Credential Manager later) via `keyring`.
* FileKeyStore: development fallback for systems without a keyring backend.
  Only used when BEJITECH_KEYSTORE=file is set.
* MemoryKeyStore: tests.
"""
from __future__ import annotations

import base64
import os
from pathlib import Path
from typing import Protocol

from bejitech.core.errors import KeyStoreError

SERVICE_NAME = "com.bejitech.licensemanager"


class KeyStore(Protocol):
    def load(self) -> bytes | None: ...
    def save(self, key: bytes) -> None: ...
    def describe(self) -> str: ...


class MemoryKeyStore:
    def __init__(self, key: bytes | None = None):
        self._key = key

    def load(self) -> bytes | None:
        return self._key

    def save(self, key: bytes) -> None:
        self._key = key

    def clear(self) -> None:
        self._key = None

    def describe(self) -> str:
        return "In-memory (tests)"


class KeychainKeyStore:
    def __init__(self, account: str):
        # account is derived from the data folder so two data folders never share a key
        self.account = account

    def load(self) -> bytes | None:
        import keyring
        from keyring.errors import KeyringError

        try:
            value = keyring.get_password(SERVICE_NAME, self.account)
        except KeyringError as exc:
            raise KeyStoreError(f"Could not read the macOS Keychain: {exc}") from exc
        return base64.b64decode(value) if value else None

    def save(self, key: bytes) -> None:
        import keyring
        from keyring.errors import KeyringError

        try:
            keyring.set_password(SERVICE_NAME, self.account, base64.b64encode(key).decode())
        except KeyringError as exc:
            raise KeyStoreError(f"Could not save to the macOS Keychain: {exc}") from exc

    def describe(self) -> str:
        return "macOS Keychain" if os.uname().sysname == "Darwin" else "System keyring"


class FileKeyStore:
    """Development only. Stores the key in a 0600 file next to the database."""

    def __init__(self, path: Path):
        self.path = path

    def load(self) -> bytes | None:
        if not self.path.exists():
            return None
        return base64.b64decode(self.path.read_text().strip())

    def save(self, key: bytes) -> None:
        self.path.write_text(base64.b64encode(key).decode())
        os.chmod(self.path, 0o600)

    def describe(self) -> str:
        return f"File (development only): {self.path}"


class EnvKeyStore:
    """Web version: the key comes from the BEJITECH_DEK environment variable (base64),
    set as a secret on the hosting service and never stored in the database.

    The key can't be written from inside the app, so save() only accepts the key that is
    already configured; anything else tells the administrator what to set."""

    VAR = "BEJITECH_DEK"

    def load(self) -> bytes | None:
        value = os.environ.get(self.VAR, "").strip()
        if not value:
            return None
        try:
            key = base64.b64decode(value, validate=True)
            if len(key) == 32:
                return key  # an exact key, e.g. the one carried over from the desktop app
        except ValueError:
            pass
        if len(value) < 32:
            raise KeyStoreError(f"{self.VAR} must be at least 32 characters long.")
        # Any long random secret (e.g. one generated by the hosting service) becomes a 256-bit key.
        import hashlib
        return hashlib.sha256(b"bejitech-dek-v1:" + value.encode()).digest()

    def save(self, key: bytes) -> None:
        if self.load() != key:
            raise KeyStoreError(
                f"The server's encryption key is not set or does not match this database. Set {self.VAR} "
                "on the hosting service to the key for this data (see the setup guide)."
            )

    def describe(self) -> str:
        return "Server secret (BEJITECH_DEK)"


class EnvFileKeyStore(EnvKeyStore):
    """Web version on your own computer: like EnvKeyStore, but a restore of a desktop-app backup
    may replace the key, which is then written back to the web.env file it came from."""

    def __init__(self, env_file: Path):
        self.env_file = Path(env_file)

    def load(self) -> bytes | None:
        # The file wins over the environment: it stays right after a restore, even across restarts.
        if self.env_file.exists():
            for line in self.env_file.read_text().splitlines():
                if line.startswith(self.VAR + "="):
                    os.environ[self.VAR] = line.split("=", 1)[1].strip()
                    break
        return super().load()

    def save(self, key: bytes) -> None:
        if self.load() == key:
            return
        value = base64.b64encode(key).decode()
        lines = self.env_file.read_text().splitlines() if self.env_file.exists() else []
        out = [ln for ln in lines if not ln.startswith(self.VAR + "=")] + [f"{self.VAR}={value}"]
        self.env_file.write_text("\n".join(out) + "\n")
        os.chmod(self.env_file, 0o600)
        os.environ[self.VAR] = value

    def describe(self) -> str:
        return f"Key file on this computer ({self.env_file})"


def default_keystore(data_root: Path) -> KeyStore:
    if os.environ.get("BEJITECH_KEYSTORE") == "env":
        return EnvKeyStore()
    if os.environ.get("BEJITECH_KEYSTORE") == "file":
        return FileKeyStore(data_root / ".dev_key")
    import hashlib

    account = "dek-" + hashlib.sha256(str(data_root.resolve()).encode()).hexdigest()[:16]
    return KeychainKeyStore(account)
