CREATE UNIQUE INDEX ux_categories_name ON categories (lower(name));
CREATE UNIQUE INDEX ux_suppliers_name ON suppliers (lower(name));
CREATE UNIQUE INDEX ux_product_lines_name ON product_lines (publisher_id, lower(name));
